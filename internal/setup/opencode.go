package setup

import (
	"encoding/json"
	"strings"
)

// openCodePlugin returns a plugin that both OpenCode generations load: OpenCode
// 2 runs setup(ctx), OpenCode 1 runs server(input). It runs the kapi home view
// once per session and adds it to the system prompt.
func openCodePlugin(command string, timeoutSeconds int) string {
	q := func(v any) string {
		b, err := json.Marshal(v)
		if err != nil {
			panic(err)
		}
		return string(b)
	}
	r := strings.NewReplacer(
		"__MARKER_LINE__", openCodeManagedPrefix+" "+Marker,
		"__COMMAND__", q(command),
		"__MARKER__", q(Marker),
		"__HEADER__", q("## kapi ambient context"),
		"__TIMEOUT__", q(timeoutSeconds*1000),
		"__ID__", q("axi-"+Marker),
	)
	return r.Replace(openCodeTemplate)
}

const openCodeTemplate = `// __MARKER_LINE__
// Generated by kapi setup hooks. Safe to edit only if you remove the marker above.
import { spawn } from "node:child_process";

const command = __COMMAND__;
const marker = __MARKER__;
const ambientHeader = __HEADER__;
const timeoutMs = __TIMEOUT__;

function runHomeView(cwd) {
  return new Promise((resolve) => {
    const child = spawn(command, [], {
      cwd: typeof cwd === "string" && cwd.length > 0 ? cwd : process.cwd(),
      env: process.env,
      shell: false,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    let settled = false;
    const timer = setTimeout(() => {
      if (settled) return;
      settled = true;
      child.kill("SIGTERM");
      resolve("error: " + marker + " ambient context timed out after " + timeoutMs + "ms");
    }, timeoutMs);
    child.stdout?.setEncoding("utf-8");
    child.stderr?.setEncoding("utf-8");
    child.stdout?.on("data", (chunk) => { stdout += chunk; });
    child.stderr?.on("data", (chunk) => { stderr += chunk; });
    child.on("error", (error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve("error: " + marker + " ambient context failed: " + error.message);
    });
    child.on("close", (code) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (code === 0) {
        resolve(stdout.trim());
        return;
      }
      resolve("error: " + marker + " ambient context failed: " + (stderr || stdout || marker + " exited with code " + code).trim());
    });
  });
}

function ambientContextFor(directory) {
  const cache = new Map();
  return async (sessionID) => {
    const key = sessionID ?? "__global__";
    let view = cache.get(key);
    if (view === undefined) {
      view = await runHomeView(directory);
      cache.set(key, view);
    }
    return view.length === 0 ? "" : ambientHeader + "\n" + view;
  };
}

export default {
  id: __ID__,
  async setup(ctx) {
    const ambientContext = ambientContextFor(ctx.location.directory);
    await ctx.session.hook("context", async (event) => {
      const text = await ambientContext(event.sessionID);
      if (text) event.system.push({ type: "text", text });
    });
  },
  async server({ directory }) {
    const ambientContext = ambientContextFor(directory);
    return {
      "experimental.chat.system.transform": async (input, output) => {
        const text = await ambientContext(input.sessionID);
        if (text) output.system.push(text);
      },
    };
  },
};
`
